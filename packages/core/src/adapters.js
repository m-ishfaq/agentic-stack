function displayCommands(commands = {}) {
  const result = {};
  for (const key of ['install', 'dev', 'test', 'testSafe', 'lint', 'typecheck', 'build']) {
    result[key] = commands[key] ?? 'not configured';
  }
  return result;
}

export function parseRule(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { body: content, paths: [] };
  const frontmatter = match[1];
  const body = content.slice(match[0].length).replace(/^\r?\n+/, '');
  const paths = [];
  const lines = frontmatter.split(/\r?\n/);
  let inPaths = false;
  for (const line of lines) {
    const inline = line.match(/^paths:\s*\[(.*)\]\s*$/);
    if (inline) {
      for (const item of inline[1].split(',')) {
        const value = item.trim().replace(/^["']|["']$/g, '');
        if (value) paths.push(value);
      }
      inPaths = false;
      continue;
    }
    if (/^paths:\s*$/.test(line)) {
      inPaths = true;
      continue;
    }
    if (inPaths) {
      const item = line.match(/^\s*-\s*(.+?)\s*$/);
      if (item) {
        paths.push(item[1].replace(/^["']|["']$/g, ''));
        continue;
      }
      if (line.trim() !== '') inPaths = false;
    }
  }
  return { body, paths };
}

function claudeRule(name, parsed, version) {
  if (parsed.paths.length === 0) return `${HEADER(version)}\n\n${parsed.body}`;
  const paths = parsed.paths.map((item) => `  - "${item}"`).join('\n');
  return `---\npaths:\n${paths}\n---\n\n${HEADER(version)}\n\n${parsed.body}`;
}

function mdc(description, content, version, paths = []) {
  if (paths.length === 0) {
    return `---\ndescription: ${description}\nalwaysApply: true\n---\n\n${HEADER(version)}\n\n${content}`;
  }
  return `---\ndescription: ${description}\nglobs: ${paths.join(',')}\nalwaysApply: false\n---\n\n${HEADER(version)}\n\n${content}`;
}

function geminiCommand(command, version) {
  const parsed = parseRule(command.content);
  const descriptionMatch = command.content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const description =
    descriptionMatch?.[1]
      ?.split(/\r?\n/)
      .find((line) => line.startsWith('description:'))
      ?.replace(/^description:\s*/, '')
      .replace(/^["']|["']$/g, '') ?? command.name;
  const prompt = parsed.body.replace(/\$ARGUMENTS/g, '{{args}}').trim();
  return `# generated by agentic-stack v${version}\ndescription = ${JSON.stringify(description)}\nprompt = """\n${prompt}\n"""\n`;
}

function codexMcp(servers, version) {
  const lines = [`# generated by agentic-stack v${version}. Edit .agents/mcp.json.`, ''];
  for (const [name, server] of Object.entries(servers)) {
    lines.push(`[mcp_servers.${name}]`);
    if (server.command) lines.push(`command = ${JSON.stringify(server.command)}`);
    if (Array.isArray(server.args)) lines.push(`args = ${JSON.stringify(server.args)}`);
    if (server.env && Object.keys(server.env).length > 0) {
      const env = Object.entries(server.env)
        .map(([key, value]) => `${JSON.stringify(key)} = ${JSON.stringify(value)}`)
        .join(', ');
      lines.push(`env = { ${env} }`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

async function safeList(dir) {
  try {
    return (await fs.readdir(dir)).sort();
  } catch {
    return [];
  }
}

async function exists(target) {
  try {
    await fs.access(target);
    return true;
  } catch {
    return false;
  }
}

function ensureNewline(text) {
  return text.endsWith('\n') ? text : `${text}\n`;
}
