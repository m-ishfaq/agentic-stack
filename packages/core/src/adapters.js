export async function installedMcpServers(root) {
  const file = path.join(root, '.agents', 'mcp.json');
  if (!(await exists(file))) return {};
  try {
    const parsed = JSON.parse(await fs.readFile(file, 'utf8'));
    return parsed.mcpServers ?? {};
  } catch {
    return {};
  }
}

export function buildAdapterFiles({
  config,
  version,
  rules = [],
  skills = [],
  commands = [],
  agents = [],
  agentsContent = '',
  mcpServers = {},
}) {
  const files = [];
  const selected = config.adapters;
  const hasMcp = Object.keys(mcpServers).length > 0;

  if (selected.includes('claude')) {
    const settings = structuredClone(CLAUDE_SETTINGS);
    settings.hooks.PostToolUse = [
      {
        matcher: 'Edit|Write|MultiEdit',
        hooks: [
          {
            type: 'command',
            command: 'node "$CLAUDE_PROJECT_DIR"/.agents/hooks/format.mjs',
          },
        ],
      },
    ];
    settings.hooks.SessionStart = [
      {
        hooks: [
          {
            type: 'command',
            command: 'node "$CLAUDE_PROJECT_DIR"/.agents/hooks/session-context.mjs',
          },
        ],
      },
    ];
    if (config.hooks?.verifyOnStop) {
      settings.hooks.Stop = [
        {
          hooks: [
            {
              type: 'command',
              command: 'node "$CLAUDE_PROJECT_DIR"/.agents/hooks/verify.mjs',
            },
          ],
        },
      ];
    }
    files.push({
      path: '.claude/settings.json',
      content: `${JSON.stringify(settings, null, 2)}\n`,
      source: 'adapter/claude',
      generated: true,
      merge: true,
    });
    for (const rule of rules) {
      const parsed = parseRule(rule.content);
      files.push({
        path: `.claude/rules/${rule.name}.md`,
        content: claudeRule(rule.name, parsed, version),
        source: `rule/${rule.name}`,
        generated: true,
      });
    }
    for (const skill of skills) {
      files.push({
        path: `.claude/skills/${skill.name}/SKILL.md`,
        content: skill.content,
        source: `skill/${skill.name}`,
        generated: true,
      });
    }
    for (const command of commands) {
      files.push({
        path: `.claude/commands/${command.name}.md`,
        content: command.content,
        source: `command/${command.name}`,
        generated: true,
      });
    }
    for (const agent of agents) {
      files.push({
        path: `.claude/agents/${agent.name}.md`,
        content: agent.content,
        source: `agent/${agent.name}`,
        generated: true,
      });
    }
    if (hasMcp) {
      files.push({
        path: '.mcp.json',
        content: `${JSON.stringify({ mcpServers }, null, 2)}\n`,
        source: 'adapter/claude',
        generated: true,
        merge: true,
      });
    }
    files.push({
      path: 'CLAUDE.md',
      content: `${HEADER(version)}\n\n# Claude Code\n\n## Response contract\n\n${RESPONSE_CONTRACT}\n\n@AGENTS.md\n`,
      source: 'adapter/claude',
      generated: true,
      merge: true,
    });
  }

  if (selected.includes('cursor')) {
    files.push(...buildCursorFiles({ rules, policy: config.policy, version, mcpServers }));
  }

  if (selected.includes('copilot')) {
    files.push(...buildCopilotFiles({ agentsContent, rules, policy: config.policy, version }));
  }

  if (selected.includes('gemini')) {
    files.push({
      path: 'GEMINI.md',
      content: `${HEADER(version)}\n\n# Gemini\n\n## Response contract\n\n${RESPONSE_CONTRACT}\n\n@AGENTS.md\n\nSkills live in \`.agents/skills/\`. Read the matching SKILL.md when a task needs a procedure. Project rules live in \`.agents/project.md\`.\n`,
      source: 'adapter/gemini',
      generated: true,
      merge: true,
    });
    for (const command of commands) {
      files.push({
        path: `.gemini/commands/${command.name}.toml`,
        content: geminiCommand(command, version),
        source: `command/${command.name}`,
        generated: true,
      });
    }
    if (hasMcp) {
      files.push({
        path: '.gemini/settings.json',
        content: `${JSON.stringify({ mcpServers }, null, 2)}\n`,
        source: 'adapter/gemini',
        generated: true,
        merge: true,
      });
    }
  }

  if (selected.includes('codex') && hasMcp) {
    files.push({
      path: '.codex/config.toml',
      content: codexMcp(mcpServers, version),
      source: 'adapter/codex',
      generated: true,
      merge: true,
    });
  }

  if (selected.includes('cline')) {
    for (const rule of rules) {
      const parsed = parseRule(rule.content);
      files.push({
        path: `.clinerules/${rule.name}.md`,
        content: `${HEADER(version)}\n\n${parsed.body}`,
        source: `rule/${rule.name}`,
        generated: true,
      });
    }
  }

  if (selected.includes('devin')) {
    for (const rule of rules) {
      const parsed = parseRule(rule.content);
      const frontmatter = parsed.paths.length
        ? `---\ntrigger: glob\nglobs: "${parsed.paths.join(',')}"\n---`
        : '---\ntrigger: always_on\n---';
      files.push({
        path: `.devin/rules/${rule.name}.md`,
        content: `${frontmatter}\n\n${HEADER(version)}\n\n${parsed.body}`,
        source: `rule/${rule.name}`,
        generated: true,
      });
    }
  }

  if (selected.includes('aider')) {
    files.push({
      path: 'CONVENTIONS.md',
      content: `${HEADER(version)}\n\n${agentsContent}`,
      source: 'adapter/aider',
      generated: true,
    });
    files.push({
      path: '.aider.conf.yml',
      content: 'read:\n  - CONVENTIONS.md\n',
      source: 'adapter/aider',
      generated: true,
    });
  }

  return files;
}

export function buildCursorFiles({ rules, policy, version, mcpServers = {} }) {
  const files = [
    {
      path: '.cursor/rules/00-policy.mdc',
      content: mdc('Project policy', policyMarkdown(policy), version),
      source: 'adapter/cursor',
      generated: true,
    },
  ];

  for (const rule of rules) {
    const parsed = parseRule(rule.content);
    files.push({
      path: `.cursor/rules/${rule.name}.mdc`,
      content: mdc(rule.name, parsed.body, version, parsed.paths),
      source: `rule/${rule.name}`,
      generated: true,
    });
  }
  if (Object.keys(mcpServers).length > 0) {
    files.push({
      path: '.cursor/mcp.json',
      content: `${JSON.stringify({ mcpServers }, null, 2)}\n`,
      source: 'adapter/cursor',
      generated: true,
      merge: true,
    });
  }
  return files;
}

export function buildCopilotFiles({ agentsContent, rules, policy, version }) {
  const files = [
    {
      path: '.github/copilot-instructions.md',
      content: `${HEADER(version)}\n\n# Copilot instructions\n\n## Response contract\n\n${RESPONSE_CONTRACT}\n\n${agentsContent}\n\n${policyMarkdown(policy)}\n`,
      source: 'adapter/copilot',
      generated: true,
    },
  ];

  for (const rule of rules) {
    const parsed = parseRule(rule.content);
    files.push({
      path: `.github/instructions/${rule.name}.instructions.md`,
      content: `---\napplyTo: "${parsed.paths.join(',') || '**'}"\n---\n\n${HEADER(version)}\n\n${parsed.body}`,
      source: `rule/${rule.name}`,
      generated: true,
    });
  }
  return files;
}

