import fs from 'node:fs/promises';
import path from 'node:path';
import { policyMarkdown } from './policy.js';
import { render } from './render.js';
import { toPosix, walk } from './util.js';

const HEADER = (version) =>
  `<!-- generated by agentic-stack v${version}. Edit .agents/ and run agentic sync. -->`;

const RESPONSE_CONTRACT = [
  'Start every response with `TLDR:` on its own line.',
  'Then one short answer or decision.',
  'Short lines. Bullets or tables. No praise, filler, em-dashes, or emoji.',
  'Report failures as failures. Say "not verified" when true.',
].join('\n');

const COPIED_DIRS = ['hooks', 'scripts', 'skills', 'commands', 'memory', 'templates', 'agents'];

export async function buildBaseFiles({ templatesBase, config, version, sourceDir, extras = {} }) {
  const files = [];
  const commands = displayCommands(config.project.commands);
  const vars = {
    project: config.project,
    commands,
    stack: config.project.stack ?? 'not detected',
    packageManager: config.project.packageManager ?? 'not detected',
    source: sourceDir,
  };

  for (const template of ['AGENTS.md', '.agents/project.md']) {
    const content = await fs.readFile(path.join(templatesBase, template), 'utf8');
    files.push({
      path: template,
      content: ensureNewline(render(content, vars)),
      source: `base/${template}`,
      generated: template === 'AGENTS.md',
      merge: template === 'AGENTS.md',
    });
  }

  for (const file of await safeList(path.join(templatesBase, '.agents', 'rules'))) {
    if (!file.endsWith('.md')) continue;
    files.push({
      path: `.agents/rules/${file}`,
      content: ensureNewline(
        await fs.readFile(path.join(templatesBase, '.agents', 'rules', file), 'utf8'),
      ),
      source: `base/.agents/rules/${file}`,
      generated: false,
    });
  }

  for (const file of ['.agents/policies/deny.json', '.agents/mcp.json']) {
    files.push({
      path: file,
      content: ensureNewline(await fs.readFile(path.join(templatesBase, file), 'utf8')),
      source: `base/${file}`,
      generated: false,
    });
  }

  for (const dir of COPIED_DIRS) {
    for (const file of await walk(path.join(templatesBase, '.agents', dir))) {
      const relative = toPosix(path.relative(templatesBase, file));
      files.push({
        path: relative,
        content: await fs.readFile(file, 'utf8'),
        source: `base/${relative}`,
        generated: false,
      });
    }
  }

  for (const file of ['.editorconfig', '.gitattributes']) {
    const full = path.join(templatesBase, file);
    if (await exists(full)) {
      files.push({
        path: file,
        content: ensureNewline(await fs.readFile(full, 'utf8')),
        source: `base/${file}`,
        generated: false,
      });
    }
  }

  if (extras.ci) {
    files.push({
      path: '.github/workflows/agentic.yml',
      content: ensureNewline(
        await fs.readFile(path.join(templatesBase, '..', 'optional', 'ci.yml'), 'utf8'),
      ),
      source: 'optional/ci.yml',
      generated: false,
    });
  }
  if (extras.devcontainer) {
    files.push({
      path: '.devcontainer/devcontainer.json',
      content: ensureNewline(
        await fs.readFile(
          path.join(templatesBase, '..', 'optional', 'devcontainer.json'),
          'utf8',
        ),
      ),
      source: 'optional/devcontainer.json',
      generated: false,
    });
  }

  return files;
}

export async function loadPackFiles(templatesBase, packs = []) {
  const files = [];
  for (const pack of packs) {
    const dir = path.join(templatesBase, '..', 'packs', pack, 'rules');
    for (const file of await safeList(dir)) {
      if (!file.endsWith('.md')) continue;
      files.push({
        path: `.agents/rules/${pack}--${file}`,
        content: ensureNewline(await fs.readFile(path.join(dir, file), 'utf8')),
        source: `pack/${pack}/${file}`,
        generated: false,
      });
    }
  }
  return files;
}

export function baseRules(baseFiles) {
  return baseFiles
    .filter((file) => file.path.startsWith('.agents/rules/') && file.path.endsWith('.md'))
    .map((file) => ({ name: path.basename(file.path, '.md'), content: file.content }));
}

export async function installedRules(root) {
  const rules = [];
  for (const file of await safeList(path.join(root, '.agents', 'rules'))) {
    if (!file.endsWith('.md')) continue;
    rules.push({
      name: file.replace(/\.md$/, ''),
      content: await fs.readFile(path.join(root, '.agents', 'rules', file), 'utf8'),
    });
  }
  return rules;
}

export async function installedSkills(root) {
  const skills = [];
  const dir = path.join(root, '.agents', 'skills');
  for (const name of await safeList(dir)) {
    const file = path.join(dir, name, 'SKILL.md');
    if (!(await exists(file))) continue;
    skills.push({ name, content: await fs.readFile(file, 'utf8') });
  }
  return skills;
}

